#!/usr/bin/env python3
"""Pack a built cart image into the C array the cartridge firmware boots from.

    ./tools/mkromh.py build/fujicfg.bin > firmware/include/fujiconfigrom.h
"""
import sys

if len(sys.argv) != 2:
    sys.exit("usage: mkromh.py <cart.bin>")

data = open(sys.argv[1], "rb").read()
# A .nes file is a 16-byte header plus whole 1K blocks: the cart parses the
# header itself, so it is baked in with the image.
if len(data) < 16 or data[:4] != b"NES\x1a" or (len(data) - 16) % 1024:
    sys.exit("%s is %d bytes: not an iNES image (16-byte header + whole 1K blocks)"
             % (sys.argv[1], len(data)))

print("/* fujiconfigrom.h -- GENERATED by tools/mkromh.py, do not edit.")
print(" *")
print(" * The console client, a whole .nes file, baked into the cartridge firmware")
print(" * as the resident image the cart installs at power-on -- there is no")
print(" * filesystem to load it from and no network yet. Rebuild with:")
print(" *   ./build.sh fujicfg && ./tools/mkromh.py build/fujicfg.nes \\")
print(" *       > firmware/include/fujiconfigrom.h")
print(" */")
print()
print("#ifndef FUJICONFIGROM_H")
print("#define FUJICONFIGROM_H")
print()
print("#define FUJI_CONFIGROM_SIZE %d" % len(data))
print()


def array(decl, b):
    print(decl + " = {")
    for i in range(0, len(b), 12):
        print("    " + " ".join("0x%02X," % x for x in b[i:i + 12]))
    print("};")
    print()


prg = data[4] * 16384
chr_ = len(data) - 16 - prg
if prg == 0 or chr_ < 0:
    sys.exit("%s: header says %d bytes of PRG, the file has %d" % (sys.argv[1], prg, len(data) - 16))
print("#define FUJI_CONFIGROM_PRG_SIZE %d" % prg)
print("#define FUJI_CONFIGROM_CHR_SIZE %d" % chr_)
print()
print("/* The whole image (the MAME device), and the cart's split: the header")
print(" * apart, PRG in SRAM 8K-aligned (the engine serves it in place), CHR left")
print(" * in flash (it only goes to RP-B, at install). Each build keeps only what")
print(" * it uses. */")
array("static const unsigned char _configrom[FUJI_CONFIGROM_SIZE]", data)
array("static const unsigned char _configrom_hdr[16]", data[:16])
array("static const unsigned char _configrom_prg[FUJI_CONFIGROM_PRG_SIZE]"
      " __attribute__((aligned(8192)))", data[16:16 + prg])
array("static const unsigned char _configrom_chr[FUJI_CONFIGROM_CHR_SIZE + 1]"
      " __attribute__((section(\".flashdata.configchr\")))", data[16 + prg:] + b"\0")
print("#endif /* FUJICONFIGROM_H */")
