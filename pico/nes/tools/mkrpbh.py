#!/usr/bin/env python3
"""Pack RP-B's SRAM image into the header RP-A carries it in.

    ./tools/mkrpbh.py ppu/build/fujines_ppu.elf > firmware/include/rpb_image.h

RP-B (pico/nes/ppu) is built no_flash: one loadable segment in SRAM. RP-A
writes it there over SWD at every boot (firmware/src/rpb_swd.c), so the
header gives the words, where they go, the entry point, the initial stack and
RP-B's status block (nes_ppu.h). The words stay in RP-A's flash: they are
read once, at boot, before any game's engine runs.
"""
import re
import struct
import subprocess
import sys

if len(sys.argv) != 2:
    sys.exit("usage: mkrpbh.py <fujines_ppu.elf>")
elf = sys.argv[1]


def run(*args):
    return subprocess.run(args, capture_output=True, text=True, check=True).stdout


# The one LOAD segment with file contents.
segs = []
for line in run("arm-none-eabi-readelf", "-lW", elf).splitlines():
    m = re.match(r"\s*LOAD\s+0x([0-9a-f]+)\s+0x([0-9a-f]+)\s+0x([0-9a-f]+)\s+0x([0-9a-f]+)", line)
    if m:
        off, vaddr, _, filesz = (int(x, 16) for x in m.groups())
        if filesz:
            segs.append((off, vaddr, filesz))
if len(segs) != 1:
    sys.exit("%s: %d loadable segments with contents; RP-B must be one (no_flash)" % (elf, len(segs)))
off, load, size = segs[0]
if load != 0x20000000:
    sys.exit("%s: loads at %#x, not 0x20000000" % (elf, load))
data = open(elf, "rb").read()[off:off + size]
data += b"\0" * (-len(data) % 4)

syms = {}
for line in run("arm-none-eabi-nm", elf).splitlines():
    parts = line.split()
    if len(parts) == 3:
        syms[parts[2]] = int(parts[0], 16)
entry = int(re.search(r"Entry point address:\s+0x([0-9a-f]+)",
                      run("arm-none-eabi-readelf", "-h", elf)).group(1), 16)
for s in ("__StackTop", "rpb_status"):
    if s not in syms:
        sys.exit("%s: no %s" % (elf, s))

words = struct.unpack("<%dI" % (len(data) // 4), data)
print("/* rpb_image.h -- GENERATED by tools/mkrpbh.py, do not edit.")
print(" *")
print(" * RP-B's firmware (pico/nes/ppu), which RP-A writes into RP-B's SRAM over")
print(" * SWD at every boot (rpb_swd.c). Kept in RP-A's flash: read once, at boot.")
print(" */")
print()
print("#ifndef RPB_IMAGE_H")
print("#define RPB_IMAGE_H")
print()
print("#include <stdint.h>")
print()
print("#define RPB_IMAGE_LOAD  0x%08Xu" % load)
print("#define RPB_IMAGE_ENTRY 0x%08Xu" % entry)
print("#define RPB_IMAGE_SP    0x%08Xu" % syms["__StackTop"])
print("#define RPB_STATUS_ADDR 0x%08Xu" % syms["rpb_status"])
print("#define RPB_IMAGE_WORDS %d" % len(words))
print()
print("static const uint32_t _rpb_image[RPB_IMAGE_WORDS]"
      " __attribute__((section(\".flashdata.rpbimage\"))) = {")
for i in range(0, len(words), 6):
    print("    " + " ".join("0x%08X," % w for w in words[i:i + 6]))
print("};")
print()
print("#endif /* RPB_IMAGE_H */")
